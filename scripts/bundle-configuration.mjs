import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import esbuild from 'esbuild';
import {bundledPackages,collectNotices} from './bundle-updater.mjs';
const projectRoot=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
export const CONFIGURATION_VENDOR='apps/desktop/src/vendor/jsonc-parser.cjs';
/** Keep the existing package boundary: one generated, licensed parser bundle,
 * no additional node_modules tree or production dependency in the package. */
export async function bundleConfiguration({root=projectRoot}={}){
 const packages=bundledPackages(root,'jsonc-parser'),{sections,missing}=collectNotices(root,packages);
 if(missing.length)throw Error('Missing JSONC parser license notice.');
 const banner=['/* Generated by scripts/bundle-configuration.mjs. Do not edit. */',...sections.map(section=>`/*\n${section.split('\n').map(line=>` * ${line}`.trimEnd()).join('\n')}\n */`)].join('\n');
 const outfile=path.join(root,CONFIGURATION_VENDOR);
 await esbuild.build({entryPoints:[path.join(root,'node_modules/jsonc-parser/lib/esm/main.js')],outfile,
  bundle:true,platform:'node',format:'cjs',target:'node20',banner:{js:banner},sourcemap:false,minify:false,logLevel:'silent'});
 const content=fs.readFileSync(outfile);
 return{relative:CONFIGURATION_VENDOR,bytes:content.length,sha256:crypto.createHash('sha256').update(content).digest('hex'),notices:sections.length};
}
if(process.argv[1]===fileURLToPath(import.meta.url))bundleConfiguration().then(result=>console.log(JSON.stringify(result))).catch(error=>{console.error(error.message);process.exitCode=1;});
